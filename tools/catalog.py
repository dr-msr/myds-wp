#!/usr/bin/env python3
"""Write docs/catalog.json and docs/CATALOG.md: every pattern, block style, template,
template part, style variation and design token in the theme, read from the files
themselves so the catalogue cannot drift.

Fails when a pattern is missing a Title, Slug, Categories, Description or Keywords.
Run through tools/build.py, or alone: python3 tools/catalog.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIRED = ("Title", "Slug", "Categories", "Description", "Keywords")
LISTS = ("Categories", "Keywords", "Block Types", "Post Types", "Template Types")


def pattern_headers() -> list[dict]:
    out, problems = [], []
    for path in sorted((ROOT / "patterns").glob("*.php")):
        head = path.read_text().split("*/", 1)[0]
        fields = dict(re.findall(r"^\s*\*\s*([A-Z][A-Za-z ]+):\s*(.+?)\s*$", head, re.M))
        missing = [f for f in REQUIRED if not fields.get(f)]
        if missing:
            problems.append(f"patterns/{path.name}: missing {', '.join(missing)}")
            continue
        entry = {"file": f"patterns/{path.name}"}
        for key, value in fields.items():
            if key == "package":
                continue
            name = key.lower().replace(" ", "_")
            entry[name] = [v.strip() for v in value.split(",")] if key in LISTS else value
        entry["inserter"] = fields.get("Inserter", "yes").lower() not in ("no", "false")
        out.append(entry)
    if problems:
        raise SystemExit("Pattern headers incomplete:\n  " + "\n  ".join(problems))
    return out


def block_styles() -> list[dict]:
    php = (ROOT / "functions.php").read_text()
    body = php.split("$styles = array(", 1)[1].split("foreach ( $styles", 1)[0]
    out = []
    for block, inner in re.findall(r"'(core/[a-z-]+)'\s*=>\s*array\((.*?)\n\t\t\t\),", body, re.S):
        for name, label in re.findall(r"'([a-z-]+)'\s*=>\s*__\(\s*'([^']+)'", inner):
            out.append({"block": block, "name": name, "class": f"is-style-{name}", "label": label})
    return out


def templates(theme: dict) -> dict:
    custom = {t["name"]: t for t in theme.get("customTemplates", [])}
    tpl = []
    for path in sorted((ROOT / "templates").glob("*.html")):
        slug = path.stem
        entry = {"slug": slug, "file": f"templates/{path.name}"}
        if slug in custom:
            entry["custom"] = True
            entry["title"] = custom[slug]["title"]
            entry["post_types"] = custom[slug].get("postTypes", [])
        tpl.append(entry)
    areas = {p["name"]: p for p in theme.get("templateParts", [])}
    parts = [
        {"slug": p.stem, "file": f"parts/{p.name}", "area": areas.get(p.stem, {}).get("area", "uncategorized"), "title": areas.get(p.stem, {}).get("title", p.stem)}
        for p in sorted((ROOT / "parts").glob("*.html"))
    ]
    return {"templates": tpl, "parts": parts}


def tokens(theme: dict) -> dict:
    s = theme["settings"]
    return {
        "colors": [{"slug": c["slug"], "name": c["name"], "css": f"var(--wp--preset--color--{c['slug']})", "token": c["color"]} for c in s["color"]["palette"]],
        "font_families": [{"slug": f["slug"], "name": f["name"]} for f in s["typography"]["fontFamilies"]],
        "font_sizes": [{"slug": f["slug"], "name": f["name"], "size": f["size"]} for f in s["typography"]["fontSizes"]],
        "spacing": [{"slug": x["slug"], "size": x["size"]} for x in s["spacing"]["spacingSizes"]],
        "radius": [{"slug": x["slug"], "size": x["size"]} for x in s["border"]["radiusSizes"]],
        "shadows": [{"slug": x["slug"], "name": x["name"]} for x in s["shadow"]["presets"]],
        "layout": s["layout"],
        "grid_classes": {
            "container": "myds-grid",
            "mobile": "myds-col-1 to myds-col-4 (4 columns, below 768px)",
            "tablet": "myds-col-md-1 to myds-col-md-8, myds-start-md-1 to myds-start-md-8 (8 columns, 768px and up)",
            "desktop": "myds-col-lg-1 to myds-col-lg-12, myds-start-lg-1 to myds-start-lg-12 (12 columns, 1024px and up)",
        },
    }


def variations() -> list[dict]:
    out = []
    for path in sorted((ROOT / "styles").glob("*.json")):
        data = json.loads(path.read_text())
        out.append({"slug": path.stem, "title": data.get("title", path.stem), "file": f"styles/{path.name}", "primary_600": data["settings"]["custom"]["myds"]["primary"]["600"]})
    return out


def markdown(cat: dict) -> str:
    md = ["# Catalogue", "", "Generated by `tools/catalog.py` from the theme files. Do not edit by hand.", ""]
    md += ["## Patterns", "", "| Slug | Title | Categories | Use | Description |", "| --- | --- | --- | --- | --- |"]
    for p in cat["patterns"]:
        use = []
        if "core/post-content" in p.get("block_types", []):
            use.append("new page")
        if p.get("block_types") and any(b.startswith("core/template-part/") for b in p["block_types"]):
            use.append("template part")
        if not p["inserter"]:
            use.append("hidden")
        md.append(f"| `{p['slug']}` | {p['title']} | {', '.join(p['categories'])} | {', '.join(use) or 'inserter'} | {p['description']} |")
    md += ["", "## Block styles", "", "| Block | Class | Label |", "| --- | --- | --- |"]
    md += [f"| `{s['block']}` | `{s['class']}` | {s['label']} |" for s in cat["block_styles"]]
    md += ["", "## Templates", "", "| Slug | File | Custom template |", "| --- | --- | --- |"]
    md += [f"| `{t['slug']}` | `{t['file']}` | {t.get('title', '')} |" for t in cat["templates"]]
    md += ["", "## Template parts", "", "| Slug | Area |", "| --- | --- |"]
    md += [f"| `{t['slug']}` | {t['area']} |" for t in cat["parts"]]
    md += ["", "## Style variations", "", "| Slug | Title | Primary 600 |", "| --- | --- | --- |"]
    md += [f"| `{v['slug']}` | {v['title']} | `{v['primary_600']}` |" for v in cat["variations"]]
    t = cat["tokens"]
    md += ["", "## Colours", "", "| Slug | Name | CSS |", "| --- | --- | --- |"]
    md += [f"| `{c['slug']}` | {c['name']} | `{c['css']}` |" for c in t["colors"]]
    md += ["", "## Font sizes", "", "| Slug | Name | Size |", "| --- | --- | --- |"]
    md += [f"| `{f['slug']}` | {f['name']} | {f['size']} |" for f in t["font_sizes"]]
    md += ["", "## Spacing, radius and shadow presets", ""]
    md.append("Spacing: " + ", ".join(f"`{x['slug']}` ({x['size']})" for x in t["spacing"]) + ".")
    md.append("")
    md.append("Radius: " + ", ".join(f"`{x['slug']}` ({x['size']})" for x in t["radius"]) + ".")
    md.append("")
    md.append("Shadow: " + ", ".join(f"`{x['slug']}`" for x in t["shadows"]) + ".")
    md += ["", "## Grid", ""]
    md += [f"- {k}: {v}" for k, v in t["grid_classes"].items()]
    md.append(f"- Content width {t['layout']['contentSize']}, wide width {t['layout']['wideSize']}.")
    return "\n".join(md) + "\n"


def main() -> None:
    theme = json.loads((ROOT / "theme.json").read_text())
    cat = {"patterns": pattern_headers(), "block_styles": block_styles(), **templates(theme), "variations": variations(), "tokens": tokens(theme)}
    if not cat["block_styles"]:
        raise SystemExit("No block styles found in functions.php; the catalogue parser needs updating.")
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "catalog.json").write_text(json.dumps(cat, indent="\t", ensure_ascii=False) + "\n")
    (docs / "CATALOG.md").write_text(markdown(cat))
    print(f"catalogue: {len(cat['patterns'])} patterns, {len(cat['block_styles'])} block styles, {len(cat['templates'])} templates, {len(cat['parts'])} parts")


if __name__ == "__main__":
    main()
