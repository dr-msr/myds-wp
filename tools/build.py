def variation(title: str, source_scale: str) -> dict:
    """A brand colour is a style variation that replaces the primary scale and nothing else."""
    return {
        "$schema": "https://schemas.wp.org/trunk/theme.json",
        "version": 3,
        "title": title,
        "settings": {"custom": {"myds": {"primary": scale(source_scale)}}},
    }


def font_size_css() -> str:
    """Line heights that belong to each MYDS type size, appended to tokens.css."""
    rules = ["/* Each MYDS type size carries its own line height. */"]
    for slug, _, _, line in FONT_SIZES:
        kebab = re.sub(r"(\d)([a-z])", r"\1-\2", slug)
        rules.append(f".has-{kebab}-font-size {{ line-height: {line}; }}")
    return "\n".join(rules) + "\n"


def main() -> None:
    (ROOT / "assets" / "css").mkdir(parents=True, exist_ok=True)
    (ROOT / "styles").mkdir(exist_ok=True)
    (ROOT / "assets" / "css" / "tokens.css").write_text(tokens_css() + "\n" + font_size_css())
    (ROOT / "theme.json").write_text(json.dumps(theme_json(), indent="\t", ensure_ascii=False) + "\n")
    for slug, title, src in (("red", "Red", "danger"), ("green", "Green", "success")):
        (ROOT / "styles" / f"{slug}.json").write_text(json.dumps(variation(title, src), indent="\t") + "\n")
    print(f"primitives {len(PRIM)}, semantic tokens {len(LIGHT)} light / {len(DARK)} dark")


if __name__ == "__main__":
    main()
