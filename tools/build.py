#!/usr/bin/env python3
"""Generate theme.json, assets/css/tokens.css and styles/*.json from the MYDS token values.

Source of truth: tools/tokens.json, our own record of the MYDS colour token values.
Run: uv run --no-project tools/build.py
Standard library only. The generated files are committed; WordPress never runs this.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

DATA = json.loads((ROOT / "tools" / "tokens.json").read_text())
PRIM: dict[str, str] = DATA["primitives"]
LIGHT = {k: (v[0], v[1]) for k, v in DATA["light"].items()}
DARK = {k: (v[0], v[1]) for k, v in DATA["dark"].items()}
assert set(LIGHT) == set(DARK), set(LIGHT) ^ set(DARK)

SCALE_STEPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"]


def scale(name: str) -> dict[str, str]:
    return {s: PRIM[f"{name}-{s}"] for s in SCALE_STEPS}


def mix(hex_a: str, alpha: float | None, over: str) -> str:
    """Flatten an alpha colour over a background, for editor swatches only."""
    if alpha is None:
        return hex_a
    a = [int(hex_a[i : i + 2], 16) for i in (1, 3, 5)]
    b = [int(over[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x * alpha + y * (1 - alpha)):02x}" for x, y in zip(a, b))


def value(ref: tuple[str, float | None]) -> str:
    prim, alpha = ref
    if alpha is None:
        return f"var(--myds-{prim})"
    return f"color-mix(in srgb, var(--myds-{prim}) {round(alpha * 100)}%, transparent)"


# ---------------------------------------------------------------- tokens.css

def block(selector: str, decls: list[str], indent: str = "") -> str:
    body = "\n".join(f"{indent}\t{d}" for d in decls)
    return f"{indent}{selector} {{\n{body}\n{indent}}}\n"


def grid_css() -> str:
    out = [
        "/* 12-8-4 grid: 4 columns and 18px gaps to 767px, 8 columns and 24px gaps from 768px, 12 columns from 1024px. */",
        ".myds-grid {\n\tdisplay: grid;\n\tgrid-template-columns: repeat(4, minmax(0, 1fr));\n\tgap: var(--myds-gap);\n}",
        ".myds-grid > * {\n\tgrid-column: 1 / -1;\n\tmin-width: 0;\n\tmargin-block: 0;\n}",
    ]
    out += [f".myds-grid > .myds-col-{n} {{ grid-column: auto / span {n}; }}" for n in range(1, 5)]
    md = ["\t.myds-grid { grid-template-columns: repeat(8, minmax(0, 1fr)); }"]
    md += [f"\t.myds-grid > .myds-col-md-{n} {{ grid-column: auto / span {n}; }}" for n in range(1, 9)]
    md += [f"\t.myds-grid > .myds-start-md-{n} {{ grid-column-start: {n}; }}" for n in range(1, 9)]
    out.append("@media (min-width: 768px) {\n" + "\n".join(md) + "\n}")
    lg = ["\t.myds-grid { grid-template-columns: repeat(12, minmax(0, 1fr)); }"]
    lg += [f"\t.myds-grid > .myds-col-lg-{n} {{ grid-column: auto / span {n}; }}" for n in range(1, 13)]
    lg += [f"\t.myds-grid > .myds-start-lg-{n} {{ grid-column-start: {n}; }}" for n in range(1, 13)]
    out.append("@media (min-width: 1024px) {\n" + "\n".join(lg) + "\n}")
    return "\n".join(out) + "\n"


def tokens_css() -> str:
    prim = []
    for name, hex_ in PRIM.items():
        if name.startswith("primary-"):
            step = name.split("-")[1]
            prim.append(f"--myds-{name}: var(--wp--custom--myds--primary--{step}, {hex_});")
        else:
            prim.append(f"--myds-{name}: {hex_};")
    light = ["color-scheme: light;"] + [f"--myds-{k}: {value(v)};" for k, v in LIGHT.items()]
    dark = ["color-scheme: dark;"] + [f"--myds-{k}: {value(v)};" for k, v in DARK.items()]
    parts = [
        "/*\n * Generated by tools/build.py from tools/tokens.json. Do not edit by hand.\n"
        " * Token names and values follow MYDS, the Malaysia Government Design System. See NOTICE.md.\n */\n",
        "/* Primitives. The primary scale reads the theme.json custom values, so a style variation can replace it. */",
        block(":root", prim),
        "/* Light */",
        block(":root", light),
        "/* Dark: chosen with the switch (class on <html>) */",
        block(":root.dark", dark),
        "/* Dark: device setting, before the script runs or without it */",
        "@media (prefers-color-scheme: dark) {\n" + block(":root:not(.light):not(.dark)", dark, "\t") + "}\n",
        grid_css(),
    ]
    return "\n".join(parts)


